const TABLES: Record<Language, Strings> = { en, 'zh-TW': zhTW, 'zh-CN': zhCN, ja, ko };

export function communityString(language: Language, key: CommunityStringKey, params?: Record<string, string | number>): string {
  const text = (TABLES[language] ?? en)[key] ?? en[key];
  return params ? text.replace(/\{(\w+)\}/g, (m, k: string) => (k in params ? String(params[k]) : m)) : text;
}

/** s(key, params) in the current app language */
export function useCommunityStrings(): (key: CommunityStringKey, params?: Record<string, string | number>) => string {
  const { language } = useLanguage();
  return useCallback((key, params) => communityString(language, key, params), [language]);
}
